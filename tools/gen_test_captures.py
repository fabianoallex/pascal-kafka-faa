#!/usr/bin/env python3
"""Generates the units of recorded test data:

  tests/Unit/Kafka.TestCaptures.pas    from tests/data/captures-*.jsonl
  tests/Unit/Kafka.TestPartitions.pas  from tests/data/partitions-java-*.tsv

The captures are the codec's test data: frames recorded from a real broker
and from the Java client. The partitions are keys and the partition the Java
producer chose for each, for 1, 3, 12 and 100 partitions (the murmur2 tests).
How both were made: docs/codec-captures.md. They are compiled into the test
executables instead of read at run time, so the tests find them from any
output folder (Win32/Win64/Debug, lib/, a Linux container) with no path to
configure.

A key goes out as the hex of its UTF-8 bytes (what murmur2 hashes), with an
ASCII label for messages: neither compiler then has to agree on how it reads
a non-ASCII literal.

Delphi caps a string literal at 255 characters, so the hex goes out in
pieces joined with "+".

    python tools/gen_test_captures.py          write the unit
    python tools/gen_test_captures.py --check  fail if it is out of date
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tests" / "data"
OUT = ROOT / "tests" / "Unit" / "Kafka.TestCaptures.pas"
OUT_PARTITIONS = ROOT / "tests" / "Unit" / "Kafka.TestPartitions.pas"
PIECE = 200


def lit(s):
    return "'" + s.replace("'", "''") + "'"


def hex_expr(h, indent):
    pieces = [h[i:i + PIECE] for i in range(0, len(h), PIECE)] or [""]
    return (" +\n" + " " * indent).join(lit(p) for p in pieces)


def generate():
    records = []
    sources = sorted(DATA.glob("captures-*.jsonl"))
    if not sources:
        raise SystemExit("no tests/data/captures-*.jsonl")
    for path in sources:
        tag = path.stem[len("captures-"):]
        for line in path.read_text(encoding="ascii").splitlines():
            if line.strip():
                r = json.loads(line)
                r["tag"] = tag
                records.append(r)
    lines = ["﻿unit Kafka.TestCaptures;", "",
             "{ Frames recorded from a real Kafka broker and from the Java client, for the",
             "  codec tests.", "",
             "  GENERATED by tools/gen_test_captures.py from " +
             ", ".join(f"tests/data/{p.name}" for p in sources) + ".",
             "  Do not edit by hand. How the captures were made: docs/codec-captures.md.", "",
             "  Each entry is a frame without its 4-byte size prefix: the request or",
             "  response header, then the body. }", "",
             "interface", "", "uses", "  SysUtils;", "",
             "type",
             "  TKafkaCapture = record",
             "    /// e.g. 'metadata-v4' or 'java-producer-metadata-v13'.",
             "    Name: string;",
             "    /// Who produced the request: 'hand-built' or the Java tool.",
             "    Source: string;",
             "    /// The Kafka tag of the broker.",
             "    KafkaTag: string;",
             "    IsRequest: Boolean;",
             "    ApiKey: Int16;",
             "    ApiVersion: Int16;",
             "    Hex: string;",
             "  end;", "",
             "const",
             f"  KAFKA_CAPTURE_COUNT = {len(records)};",
             f"  KAFKA_CAPTURES: array[0..{len(records) - 1}] of TKafkaCapture = ("]
    rows = []
    for r in records:
        rows.append(
            f"    (Name: {lit(r['name'])}; Source: {lit(r['source'])}; KafkaTag: {lit(r['tag'])};\n"
            f"     IsRequest: {'True' if r['dir'] == 'request' else 'False'}; "
            f"ApiKey: {r['api_key']}; ApiVersion: {r['api_version']};\n"
            f"     Hex: {hex_expr(r['hex'], 10)})")
    lines.append(",\n".join(rows))
    lines += ["  );", "",
              "/// The capture's bytes.",
              "function KafkaCaptureBytes(const ACapture: TKafkaCapture): TBytes;",
              "/// The index of the request (AIsRequest) or response named AName; -1 if none.",
              "function KafkaFindCapture(const AName: string; AIsRequest: Boolean): Integer;",
              "",
              "implementation",
              "",
              "function HexValue(C: Char): Integer;",
              "begin",
              "  case C of",
              "    '0'..'9': Result := Ord(C) - Ord('0');",
              "    'a'..'f': Result := Ord(C) - Ord('a') + 10;",
              "    'A'..'F': Result := Ord(C) - Ord('A') + 10;",
              "  else",
              "    raise EConvertError.CreateFmt('Not a hex digit: %s', [C]);",
              "  end;",
              "end;",
              "",
              "function KafkaCaptureBytes(const ACapture: TKafkaCapture): TBytes;",
              "var",
              "  I: Integer;",
              "begin",
              "  Result := nil;",
              "  SetLength(Result, Length(ACapture.Hex) div 2);",
              "  for I := 0 to High(Result) do",
              "    Result[I] := Byte(HexValue(ACapture.Hex[2 * I + 1]) * 16 +",
              "      HexValue(ACapture.Hex[2 * I + 2]));",
              "end;",
              "",
              "function KafkaFindCapture(const AName: string; AIsRequest: Boolean): Integer;",
              "var",
              "  I: Integer;",
              "begin",
              "  for I := Low(KAFKA_CAPTURES) to High(KAFKA_CAPTURES) do",
              "    if (KAFKA_CAPTURES[I].Name = AName) and (KAFKA_CAPTURES[I].IsRequest = AIsRequest) then",
              "      Exit(I);",
              "  Result := -1;",
              "end;",
              "",
              "end."]
    return "\n".join(lines) + "\n"


def split_lit(s, indent):
    """A literal of any length: Delphi caps one at 255 characters."""
    pieces = [s[i:i + PIECE] for i in range(0, len(s), PIECE)] or [""]
    return (" +" + chr(10) + " " * indent).join(lit(p) for p in pieces)


def ascii_label(s):
    return "".join(c if 32 <= ord(c) < 127 else f"\\u{ord(c):04x}" for c in s)


def generate_partitions():
    sources = sorted(DATA.glob("partitions-java-*.tsv"))
    if not sources:
        raise SystemExit("no tests/data/partitions-java-*.tsv")
    rows = []
    for path in sources:
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            key, *parts = line.split("\t")
            rows.append((key, [int(x) for x in parts]))
    lines = ["\ufeffunit Kafka.TestPartitions;", "",
             "{ Keys and the partition the Java producer chose for each, for the murmur2",
             "  tests.", "",
             "  GENERATED by tools/gen_test_captures.py from " +
             ", ".join(f"tests/data/{p.name}" for p in sources) + ".",
             "  Do not edit by hand. How it was made: docs/codec-captures.md. A key is the",
             "  hex of its UTF-8 bytes; Label is the key with non-ASCII characters as",
             "  \\uXXXX, for messages. }", "",
             "interface", "",
             "type",
             "  TKafkaJavaPartition = record",
             "    Label_: string;",
             "    KeyHex: string;",
             "    /// The partition among 1, 3, 12 and 100.",
             "    Of1, Of3, Of12, Of100: Integer;",
             "  end;", "",
             "const",
             f"  KAFKA_JAVA_PARTITION_COUNT = {len(rows)};",
             f"  KAFKA_JAVA_PARTITIONS: array[0..{len(rows) - 1}] of TKafkaJavaPartition = ("]
    out = []
    for key, ps in rows:
        out.append(f"    (Label_: {split_lit(ascii_label(key), 13)};\n"
                   f"     KeyHex: {hex_expr(key.encode('utf-8').hex(), 13)};\n"
                   f"     Of1: {ps[0]}; Of3: {ps[1]}; Of12: {ps[2]}; Of100: {ps[3]})")
    lines.append(",\n".join(out))
    lines += ["  );", "", "implementation", "", "end."]
    return "\n".join(lines) + "\n"


def main(argv):
    stale = 0
    for out, text in ((OUT, generate()), (OUT_PARTITIONS, generate_partitions())):
        data = text.encode("utf-8")
        if out.exists() and out.read_bytes() == data:
            continue
        if "--check" in argv:
            print(f"out of date: {out.relative_to(ROOT)} (run python tools/gen_test_captures.py)")
            stale = 1
        else:
            out.write_bytes(data)
            print(f"wrote {out.relative_to(ROOT)}")
    return stale


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
